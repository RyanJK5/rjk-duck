#!/usr/bin/env python3
"""Formats src/ and tests/ with clang-format, or checks them with --check.

CI uses clang-format 23.1.5 (pip install clang-format==23.1.5); other versions
may format some code differently. Files generated by generate_operators.py are
left alone.
"""

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = ["src/*.hpp", "tests/*.cpp", "tests/*.hpp", ":!src/generated/*"]
VERSION = "23.1.5"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="report unformatted files instead of formatting them")
    parser.add_argument("--clang-format", default=os.environ.get("CLANG_FORMAT", "clang-format"),
                        help="clang-format executable (default: $CLANG_FORMAT or clang-format)")
    args = parser.parse_args()

    exe = shutil.which(args.clang_format)
    if exe is None:
        sys.exit(f"{args.clang_format} not found; install it with: pip install clang-format=={VERSION}")

    version = subprocess.run([exe, "--version"], capture_output=True, text=True).stdout
    if VERSION not in version:
        print(f"warning: CI uses clang-format {VERSION}, found: {version.strip()}", file=sys.stderr)

    files = subprocess.run(["git", "ls-files", *FILES], cwd=ROOT, check=True,
                           capture_output=True, text=True).stdout.split()
    command = [exe, "--dry-run", "--Werror"] if args.check else [exe, "-i"]
    return subprocess.run([*command, *files], cwd=ROOT).returncode


if __name__ == "__main__":
    sys.exit(main())
